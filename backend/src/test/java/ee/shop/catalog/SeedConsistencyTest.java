package ee.shop.catalog;

import ee.shop.support.IntegrationTest;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;

import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * The seeded database has to be TRUE, not merely populated.
 *
 * Both failures below share a shape worth naming: neither one breaks anything
 * visibly. A missing rendition falls back to the original image, and a review
 * without a matching order still renders. Nothing 500s, no test that asserts a
 * happy path goes red — the data is just quietly wrong, and stays wrong until
 * somebody reads the tables. That is precisely the kind of defect that needs an
 * assertion rather than a look.
 */
@Tag("api")
class SeedConsistencyTest extends IntegrationTest {

    @Autowired JdbcTemplate jdbc;

    /**
     * Multi-size images are generated by the upload endpoint, so for a long
     * time every seeded image had NULL thumbnail_key and medium_key — the
     * capability was real, tested, and completely invisible on a fresh clone,
     * where seeded images are the ONLY images that exist.
     * SeededImageRenditionBackfill closes that at startup; this proves it ran.
     *
     * Two exclusions, both deliberate, because a NULL rendition is a correct
     * answer in each case and asserting otherwise would assert a behaviour the
     * code does not have:
     *
     *  - SVG. A vector scales to any size on its own, and ImageIO cannot decode
     *    one anyway.
     *  - Anything under product-images/uploads/. Those are not seed data at all;
     *    they are rows the upload tests create in this shared database, and one
     *    of them uploads an image already smaller than every target size
     *    specifically to assert it gets NO renditions
     *    (ProductImageControllerTest.aTinyImage_getsNoRenditions...). Without
     *    this clause that sibling test's fixture fails THIS one, which is how
     *    the over-broad first version of this assertion was found.
     */
    @Test
    void everySeededRasterImageHasSmallerRenditions() {
        List<Map<String, Object>> missing = jdbc.queryForList("""
                SELECT storage_key
                  FROM product_images
                 WHERE thumbnail_key IS NULL
                   AND medium_key IS NULL
                   AND lower(storage_key) NOT LIKE '%.svg'
                   AND storage_key NOT LIKE 'product-images/uploads/%'
                """);

        assertThat(missing)
                .as("seeded raster images with no smaller rendition: %s", missing)
                .isEmpty();
    }

    /**
     * The shop advertises that only verified purchasers may review. The seeded
     * reviews were inserted directly, bypassing that rule — which was fine for
     * the rule itself (it still holds for anything submitted through the API)
     * but left the seed contradicting the claim: twenty people had written
     * reviews and bought nothing.
     *
     * This asserts the seed now satisfies the SAME condition
     * ReviewRepository.hasPurchased enforces, folded the same way: the order's
     * most recent STATUS event decides its status — never INVOICE_ISSUED, which
     * is a fact about the order, not a status — because status is derived and
     * never stored (DECISIONS.md §1). Copying the condition rather than calling
     * the repository is deliberate — if the two ever disagree, that disagreement
     * is what this should catch, which is exactly what happened here: adding
     * INVOICE_ISSUED (appended right after every payment) broke this copy
     * without anyone noticing until the two were compared again.
     */
    @Test
    void everySeededReviewTracesToAPaidOrderForThatProduct() {
        List<Map<String, Object>> unbacked = jdbc.queryForList("""
                SELECT r.user_id, r.product_id
                  FROM reviews r
                 WHERE NOT EXISTS (
                       SELECT 1
                         FROM order_lines ol
                         JOIN orders o ON o.id = ol.order_id
                        WHERE ol.product_id = r.product_id
                          AND o.user_id = r.user_id
                          AND (
                              SELECT e.event_type
                                FROM order_events e
                               WHERE e.order_id = o.id
                                 AND e.event_type <> 'INVOICE_ISSUED'
                               ORDER BY e.occurred_at DESC
                               LIMIT 1
                          ) IN ('PAID', 'SHIPPED', 'DELIVERED')
                 )
                """);

        assertThat(unbacked)
                .as("reviews from customers with no paid order for that product: %s", unbacked)
                .isEmpty();
    }

    /**
     * Guards on the two guards above. Both assert that a query returns NOTHING,
     * which an empty table satisfies just as well as a correct one — so each
     * needs proof there was something to check in the first place.
     */
    @Test
    void theSeedActuallyContainsReviews() {
        assertThat(jdbc.queryForObject("SELECT count(*) FROM reviews", Integer.class))
                .isGreaterThan(100);
    }

    @Test
    void theSeedActuallyContainsRasterImages() {
        assertThat(jdbc.queryForObject("""
                SELECT count(*)
                  FROM product_images
                 WHERE lower(storage_key) NOT LIKE '%.svg'
                   AND storage_key NOT LIKE 'product-images/uploads/%'
                """, Integer.class))
                .as("with no raster images seeded, the rendition assertion would be vacuous")
                .isPositive();
    }
}
