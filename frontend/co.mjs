import { chromium } from '@playwright/test';
const b = await chromium.launch();
const c = await b.newContext({ viewport: { width: 1280, height: 1100 } });
const p = await c.newPage();
const errs = [];
p.on('pageerror', e => errs.push(e.message));
const res = await p.request.get('http://localhost:5173/api/products?limit=20');
const items = (await res.json()).items.filter(i => i.stockQuantity > 0);
await p.goto('http://localhost:5173/products/' + items[0].slug, { waitUntil: 'load' });
await p.waitForTimeout(1800);
await p.locator('.add-to-cart button').click();
await p.waitForTimeout(1500);
await p.goto('http://localhost:5173/checkout', { waitUntil: 'load' });
await p.waitForTimeout(2000);
const legend = await p.locator('.delivery-options legend').textContent().catch(() => null);
const opts = await p.locator('.delivery-option').count();
const checked = await p.locator('.delivery-option input:checked').count();
console.log('delivery fieldset legend:', legend);
console.log('options rendered:', opts, '| preselected:', checked);
console.log('submit button:', (await p.locator('button[type=submit]').textContent().catch(()=> '?')).trim());
console.log('summary total:', (await p.locator('.order-total-grand').textContent().catch(()=> '?')).trim());
console.log(errs.length ? 'PAGE ERRORS: ' + errs.join(' | ') : 'no page errors');
await p.screenshot({ path: process.argv[2], fullPage: true });
await b.close();
